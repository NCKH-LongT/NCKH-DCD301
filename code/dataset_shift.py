"""B2 — how different are M5 and VN1? Feature-level comparison of the evaluated series.

For each test window the per-series features of f2d/series_features.py are computed from the history before
the test period (no test information). Reported:
    1. median and quartiles of every feature in M5 and VN1
    2. two-sample Kolmogorov–Smirnov distance and population stability index (PSI, pooled deciles)
    3. single-feature separability: AUC of the feature alone for telling the two datasets apart (0.5 = identical)
    4. overall separability: 5-fold cross-validated AUC of a gradient-boosting classifier "M5 or VN1?" on a balanced
       sample, with all features and with the shared, scale-free features only; permutation importance
    5. PCA of the standardised shared features (figure)
Writes code/outputs/dataset_shift.md, dataset_shift.csv, fig_dataset_shift.png and the feature tables
data/cache/series_features_<DATASET>_<window>.parquet (reused by the segmentation step).

Usage:
    python code/dataset_shift.py
"""
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats
from sklearn.decomposition import PCA
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.inspection import permutation_importance
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import classify, config, data  # noqa: E402
from f2d.series_features import FEATURES, SHARED, series_features  # noqa: E402

OFFSETS = (0, 26, 52)
N_BAL = 9000          # series per dataset in the balanced samples
SEED = config.SEED


def table(name, offset):
    p = data.load(name)
    if offset:
        p = data.truncate(p, p["Y"].shape[1] - offset)
    Y = p["Y"]
    cutoff = Y.shape[1] - config.TEST_WEEKS
    sel = p["start"] <= cutoff - config.VALID_WEEKS
    cls, _, _ = classify.classify(Y, p["start"], cutoff)
    sel &= cls != "none"
    f = series_features(p, cutoff)
    f.insert(0, "demand_class", cls)
    f.insert(0, "series_id", p["attrs"]["series_id"].to_numpy())
    f = f[sel].reset_index(drop=True)
    w = f"w{offset}" if offset else "main"
    f.to_parquet(os.path.join(config.CACHE, f"series_features_{name}_{w}.parquet"), index=False)
    return f


def psi(a, b, bins=10):
    a, b = a[np.isfinite(a)], b[np.isfinite(b)]
    edges = np.unique(np.quantile(np.r_[a, b], np.linspace(0, 1, bins + 1)))
    if len(edges) < 3:
        return np.nan
    pa = np.histogram(a, edges)[0] / len(a) + 1e-4
    pb = np.histogram(b, edges)[0] / len(b) + 1e-4
    return float(((pa - pb) * np.log(pa / pb)).sum())


def compare(m5, vn1):
    rows = []
    for c in FEATURES:
        a, b = m5[c].to_numpy(float), vn1[c].to_numpy(float)
        fa, fb = a[np.isfinite(a)], b[np.isfinite(b)]
        ks = stats.ks_2samp(fa, fb).statistic if len(fa) and len(fb) else np.nan
        y = np.r_[np.zeros(len(fa)), np.ones(len(fb))]
        auc = roc_auc_score(y, np.r_[fa, fb]) if len(fa) and len(fb) else np.nan
        q = lambda v: np.nanpercentile(v, [25, 50, 75]) if np.isfinite(v).any() else [np.nan] * 3
        qa, qb = q(a), q(b)
        rows.append(dict(feature=c, M5_median=qa[1], M5_q25=qa[0], M5_q75=qa[2], VN1_median=qb[1], VN1_q25=qb[0],
                         VN1_q75=qb[2], KS=ks, PSI=psi(a, b), AUC_single=max(auc, 1 - auc),
                         M5_missing=float(np.mean(~np.isfinite(a))), VN1_missing=float(np.mean(~np.isfinite(b)))))
    return pd.DataFrame(rows)


def balanced(m5, vn1, rng):
    a = m5.iloc[rng.choice(len(m5), min(N_BAL, len(m5)), replace=False)]
    b = vn1.iloc[rng.choice(len(vn1), min(N_BAL, len(vn1)), replace=False)]
    X = pd.concat([a, b], ignore_index=True)
    y = np.r_[np.zeros(len(a)), np.ones(len(b))]
    return X, y


def domain_auc(X, y, cols):
    clf = HistGradientBoostingClassifier(max_iter=200, learning_rate=0.1, random_state=SEED)
    cv = StratifiedKFold(5, shuffle=True, random_state=SEED)
    pr = cross_val_predict(clf, X[cols].to_numpy(float), y, cv=cv, method="predict_proba")[:, 1]
    return roc_auc_score(y, pr)


def main():
    rng = np.random.default_rng(SEED)
    lines = ["# B2 — Differences between M5 and VN1 (generated by code/dataset_shift.py)", "",
             "Evaluated series only; every feature is computed from the history before the test period.", ""]
    allrows, aucs = [], []
    main_tables = None
    for off in OFFSETS:
        w = f"w{off}" if off else "main"
        m5, vn1 = table("M5", off), table("VN1", off)
        t = compare(m5, vn1)
        t.insert(0, "window", w)
        allrows.append(t)
        X, y = balanced(m5, vn1, rng)
        aucs.append(dict(window=w, n_M5=len(m5), n_VN1=len(vn1), AUC_all_features=domain_auc(X, y, FEATURES),
                         AUC_shared_features=domain_auc(X, y, SHARED),
                         AUC_adi_cv2_only=domain_auc(X, y, ["adi", "cv2"])))
        if off == 0:
            main_tables = (m5, vn1, X, y)
    res = pd.concat(allrows, ignore_index=True)
    res.to_csv(os.path.join(config.OUTPUTS, "dataset_shift.csv"), index=False)

    t0 = res[res.window == "main"].drop(columns="window").sort_values("KS", ascending=False)
    lines += ["## 1. Feature by feature, main window (sorted by KS distance)", "",
              "KS = Kolmogorov–Smirnov distance (0 = same distribution, 1 = disjoint). PSI > 0.25 is usually read as a "
              "large shift. AUC_single = how well the feature alone tells the datasets apart (0.5 = not at all).", "",
              t0.round(3).to_markdown(index=False), ""]
    ks = res.pivot(index="feature", columns="window", values="KS")[[f"w{o}" if o else "main" for o in OFFSETS]]
    lines += ["## 2. KS distance in the three test windows", "", ks.loc[t0.feature].round(3).to_markdown(), ""]
    lines += ["## 3. Overall separability (classifier “M5 or VN1?”, 5-fold CV, balanced sample)", "",
              "shared features = " + ", ".join(SHARED) + " (no history length, no price, no seasonality feature that "
              "needs 104 weeks).", "", pd.DataFrame(aucs).round(3).to_markdown(index=False), ""]

    m5, vn1, X, y = main_tables
    clf = HistGradientBoostingClassifier(max_iter=200, learning_rate=0.1, random_state=SEED)
    idx = rng.permutation(len(y))
    tr, te = idx[: int(0.7 * len(y))], idx[int(0.7 * len(y)):]
    clf.fit(X[SHARED].to_numpy(float)[tr], y[tr])
    pi = permutation_importance(clf, X[SHARED].to_numpy(float)[te], y[te], scoring="roc_auc", n_repeats=5, random_state=SEED)
    imp = pd.DataFrame({"feature": SHARED, "AUC_drop_when_permuted": pi.importances_mean}).sort_values(
        "AUC_drop_when_permuted", ascending=False)
    lines += ["## 4. Which shared features carry the difference (permutation importance, main window)", "",
              imp.round(3).to_markdown(index=False), ""]

    # demand classes
    cls = pd.DataFrame({"M5": m5.demand_class.value_counts(normalize=True), "VN1": vn1.demand_class.value_counts(normalize=True)})
    lines += ["## 5. ADI–CV² class shares, main window", "", (100 * cls).round(1).to_markdown(), ""]

    # PCA figure on the shared features (median-imputed, robust-scaled on the pooled balanced sample)
    Z = X[SHARED].to_numpy(float)
    med = np.nanmedian(Z, 0)
    Z = np.where(np.isfinite(Z), Z, med)
    iqr = np.subtract(*np.percentile(Z, [75, 25], 0))
    Z = np.clip((Z - med) / np.where(iqr > 0, iqr, 1), -5, 5)
    pca = PCA(2, random_state=SEED).fit(Z)
    S = pca.transform(Z)
    fig, ax = plt.subplots(figsize=(6, 4.5))
    for lab, name, col in ((0, "M5", "#1f77b4"), (1, "VN1", "#d62728")):
        m = y == lab
        ax.scatter(S[m, 0], S[m, 1], s=3, alpha=0.25, color=col, label=name)
    ax.set_xlabel(f"PC1 ({100 * pca.explained_variance_ratio_[0]:.0f}% of variance)")
    ax.set_ylabel(f"PC2 ({100 * pca.explained_variance_ratio_[1]:.0f}%)")
    ax.set_title("Series features before the main test window (shared features)")
    leg = ax.legend(markerscale=4)
    for h in leg.legend_handles:
        h.set_alpha(1)
    ax.grid(alpha=.3)
    fig.tight_layout()
    fig.savefig(os.path.join(config.OUTPUTS, "fig_dataset_shift.png"), dpi=150)
    load = pd.DataFrame(pca.components_.T, index=SHARED, columns=["PC1", "PC2"])
    lines += ["## 6. PCA of the shared features (main window)", "", "![PCA](fig_dataset_shift.png)", "",
              "Loadings:", "", load.round(2).to_markdown(), ""]
    with open(os.path.join(config.OUTPUTS, "dataset_shift.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("written code/outputs/dataset_shift.md")


if __name__ == "__main__":
    main()
