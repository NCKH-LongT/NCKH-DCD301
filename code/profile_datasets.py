"""Profile the two datasets used in the study (M5 and the Vietnam footwear retail dataset).

Writes code/outputs/data_profile.md. All numbers quoted in 03_problem_and_gap and
04_proposed_system come from this report.

Usage:
    python code/profile_datasets.py
"""
import glob
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
M5_DIR = os.path.join(DATA, "m5-forecasting-accuracy")
VN_DIR = os.path.join(DATA, "vietnamsaleandinventory", "InventoryAndSale_snapshot_data")
CACHE = os.path.join(DATA, "cache")
OUT = os.path.join(ROOT, "code", "outputs", "data_profile.md")

# Syntetos et al. (2005) thresholds as used in the M5 background paper (paper 01, p. 7-8).
ADI_CUT, CV2_CUT = 4 / 3, 0.5

lines = []


def log(text=""):
    print(text)
    lines.append(text)


def classify(adi, cv2):
    return np.where(adi < ADI_CUT, np.where(cv2 < CV2_CUT, "smooth", "erratic"),
                    np.where(cv2 < CV2_CUT, "intermittent", "lumpy"))


def matrix_profile(M, label):
    """M: series x periods array of non-negative demand."""
    nz = M > 0
    nnz = nz.sum(1)
    adi = M.shape[1] / np.maximum(nnz, 1)
    mean = np.where(nnz > 0, (M * nz).sum(1) / np.maximum(nnz, 1), np.nan)
    var = np.where(nnz > 0, ((np.where(nz, M, 0) - mean[:, None] * nz) ** 2).sum(1) / np.maximum(nnz, 1), np.nan)
    cls = classify(adi, var / mean ** 2)
    share = pd.Series(cls[nnz > 0]).value_counts(normalize=True).mul(100).round(1).to_dict()
    log(f"| {label} | {M.shape[0]:,} | {M.shape[1]} | {1 - nz.mean():.1%} | {np.median(adi):.2f} | {share} |")


def panel_profile(df, keys, periods, label):
    """df: long table with keys + 'week' + 'qty'."""
    g = df.groupby(keys + ["week"])["qty"].sum().reset_index()
    pos = g[g["qty"] > 0]
    n = g.groupby(keys).ngroups
    st = pos.groupby(keys)["qty"].agg(nnz="size", mean="mean", std=lambda x: x.std(ddof=0))
    adi = len(periods) / st["nnz"]
    cls = classify(adi.to_numpy(), ((st["std"] / st["mean"]) ** 2).to_numpy())
    share = pd.Series(cls).value_counts(normalize=True).mul(100).round(1).to_dict()
    log(f"| {label} | {n:,} | {len(periods)} | {1 - len(pos) / (n * len(periods)):.1%} | {adi.median():.2f} | {share} |")


def read_xlsx_folder(sub, cache_name):
    path = os.path.join(CACHE, cache_name)
    if os.path.exists(path):
        return pd.read_parquet(path)
    parts = []
    for f in sorted(glob.glob(os.path.join(VN_DIR, sub, "*.xlsx"))):
        d = pd.read_excel(f, engine="calamine")
        d["src_file"] = os.path.basename(f)
        parts.append(d)
    df = pd.concat(parts, ignore_index=True)
    df.columns = [str(c).strip() for c in df.columns]
    for c in df.columns:
        if df[c].dtype == object:
            df[c] = df[c].astype(str)
    os.makedirs(CACHE, exist_ok=True)
    df.to_parquet(path)
    return df


def main():
    log("# Data profile (generated by code/profile_datasets.py)")
    log()
    log(f"ADI–CV² thresholds: ADI = 4/3, CV² = 0.5. ADI is computed over the full period grid, including weeks before a product's first sale.")
    log()

    # ---------------- M5 ----------------
    m5 = pd.read_csv(os.path.join(M5_DIR, "sales_train_evaluation.csv"))
    cal = pd.read_csv(os.path.join(M5_DIR, "calendar.csv"))
    dcols = [c for c in m5.columns if c.startswith("d_")]
    Y = m5[dcols].to_numpy(dtype=np.float32)
    wk = cal["wm_yr_wk"].iloc[: len(dcols)].to_numpy()
    uw, inv = np.unique(wk, return_inverse=True)
    W = np.stack([Y[:, inv == j].sum(1) for j in range(len(uw))], axis=1)
    log("## 1. M5")
    log()
    log(f"- Series (item × store): {len(m5):,}; items: {m5.item_id.nunique():,}; stores: {m5.store_id.nunique()}; days: {len(dcols)} ({cal.date.iloc[0]} → {cal.date.iloc[len(dcols) - 1]}); Walmart weeks: {len(uw)}")
    log()
    log("| Level | Series | Periods | Zero share | Median ADI | Demand classes (%) |")
    log("|---|---|---|---|---|---|")
    matrix_profile(Y, "M5 item × store, daily")
    matrix_profile(W, "M5 item × store, weekly")
    log()

    # ---------------- Vietnam ----------------
    s = read_xlsx_folder("Sales_snapshot_data", "vn_sales.parquet")
    for c in ["sold_quantity", "cost_price", "net_price", "week", "site", "branch_id"]:
        s[c] = pd.to_numeric(s[c], errors="coerce")
    pm = pd.read_excel(os.path.join(VN_DIR, "MasterData", "Productmaster.xlsx"), engine="calamine")
    pm["listing_price"] = pd.to_numeric(pm["listing_price"], errors="coerce")
    s = s.merge(pm[["product_id", "mold_code", "color", "listing_price", "product_group"]], on="product_id", how="left")
    s["style_color"] = s["mold_code"].astype(str) + "_" + s["color"].astype(str)

    log("## 2. Vietnam footwear retail (Vietnam Datathon 2023, Dataset 2)")
    log()
    log(f"- Sales rows: {len(s):,}; monthly files: {s.src_file.nunique()}; weeks: {s.week.nunique()} ({int(s.week.min())} → {int(s.week.max())}); sites: {s.site.nunique()}; SKUs: {s.product_id.nunique():,}; styles (mold_code): {s.mold_code.nunique()}; style-colours: {s.style_color.nunique():,}")
    log(f"- Rows with negative quantity (returns): {int((s.sold_quantity < 0).sum()):,}; rows in anomalous week 202352: {int((s.week == 202352).sum()):,}")
    log(f"- Distribution channels (rows): {s.distribution_channel.value_counts().to_dict()}")
    log(f"- Product groups (rows): {s.product_group.value_counts().to_dict()}")
    r = s[(s.sold_quantity > 0) & (s.listing_price > 0) & (s.distribution_channel == "Bán lẻ")]
    ratio = (r.net_price / r.sold_quantity) / r.listing_price
    log(f"- Retail unit net price / listing price, quantiles: {ratio.quantile([.05, .25, .5, .75, .95]).round(2).to_dict()}; share of units sold ≥30% below listing: {np.average(ratio <= .7, weights=r.sold_quantity):.1%}")
    log(f"- Retail unit cost / listing price, median: {((r.cost_price / r.sold_quantity) / r.listing_price).median():.2f}")
    log()

    s = s[s.week != 202352].copy()
    s["qty"] = s["sold_quantity"].clip(lower=0)
    weeks = sorted(s.week.dropna().unique())
    retail = s[s.distribution_channel == "Bán lẻ"]
    log("| Level (retail channel, weekly) | Series | Periods | Zero share | Median ADI | Demand classes (%) |")
    log("|---|---|---|---|---|---|")
    panel_profile(retail, ["product_id", "site"], weeks, "VN SKU × store")
    panel_profile(retail, ["style_color", "site"], weeks, "VN style-colour × store")
    panel_profile(retail, ["mold_code", "site"], weeks, "VN style × store")
    panel_profile(retail, ["style_color"], weeks, "VN style-colour × chain")
    panel_profile(retail, ["mold_code"], weeks, "VN style × chain")
    log()

    inv = read_xlsx_folder("Inventory_snapshot_data", "vn_inventory.parquet")
    inv["quantity"] = pd.to_numeric(inv["quantity"], errors="coerce")
    inv["plant"] = pd.to_numeric(inv["plant"], errors="coerce")
    per = inv.groupby("src_file").agg(rows=("quantity", "size"), units=("quantity", "sum"), plants=("plant", "nunique"))
    log("## 3. Vietnam inventory snapshots")
    log()
    log(f"- Snapshot files: {inv.src_file.nunique()} (month-end, 2022 only); plants: {inv.plant.nunique()}; plants present in all snapshots: {int((inv.groupby('plant').src_file.nunique() == inv.src_file.nunique()).sum())}")
    log()
    log(per.to_markdown())
    log()
    jan = inv[inv.src_file.str.startswith("31-01-2022")].groupby("plant").quantity.sum()
    sales22 = s[(s.week >= 202201) & (s.week <= 202252)].groupby("site").qty.sum()
    cmp = pd.DataFrame({"stock_jan2022": jan, "units_sold_2022": sales22.reindex(jan.index)}).fillna(0)
    cmp["weeks_of_supply"] = (cmp.stock_jan2022 / (cmp.units_sold_2022 / 52)).round(1)
    log("Stock at end of Jan-2022 vs units sold in 2022 at the same site code (all channels):")
    log()
    log(cmp.to_markdown())
    log()
    log("Note: weeks of supply of several hundred weeks suggest either extreme overstock or that the sales files (`*_split_1.xlsx`) contain only part of the transactions.")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
