"""P1-4: sensitivity of the main findings to the stock-out detector threshold and the imputation rule
(design: phase5_workflow.md, section 8).

α ∈ {0.001, 0.01, 0.05, 0.1} (censoring_check.flag_weeks) × imputation of flagged test weeks:
    mean  max(sales, mean weekly sales before the test period)          (paper)
    half  max(sales, half of that mean)
    pos   max(sales, mean of the positive weekly sales before the test)  (strong scenario)
Reported per scenario: leading single method (frontier rank) per run, Δ TSB-NB vs LGB-Q on M5 and Δ E7-med vs LGB-Q
at fill 0.92 (ranges over windows), and the maximum regret over the six runs of E7-med, C2 and LGB-Q.
Writes code/outputs/censoring/censoring_sensitivity.md and .csv.

Usage:
    python code/censoring_sensitivity.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_results import frontier_rank  # noqa: E402
from censoring_check import flag_weeks  # noqa: E402
from f2d import config  # noqa: E402
from robust_common import LAB, METHODS, WINDOWS, load_window, run  # noqa: E402
from segment_eval import MODELS, TARGETS, inv_at  # noqa: E402

ALPHAS = (0.001, 0.01, 0.05, 0.1)
RULES = ("mean", "half", "pos")
QS = list(config.QUANTILES)


def need_table(D, Q):
    dem = D[:, config.WARMUP_WEEKS:].sum()
    rows = {}
    for m in METHODS:
        f, i = [], []
        for t in config.TAU_GRID:
            s, o = run(D, Q[m][:, :, QS.index(t)])
            f.append(s.sum() / dem), i.append(o.sum() / dem)
        f = np.maximum.accumulate(np.array(f))
        rows[m] = [inv_at(f, np.array(i), tg) for tg in TARGETS]
    return pd.DataFrame(rows, index=TARGETS)


def summarise(need):
    best = need[MODELS].min(axis=1)
    reg = {m: (need[m] / best - 1).mean(skipna=True) for m in METHODS}
    lead = LAB[frontier_rank(need[MODELS].T).idxmin()]
    d = lambda m: need.loc[0.92, m] / need.loc[0.92, "lgb_quantile"] - 1
    return dict(leader=lead, d_tsb=d("tsb_nb"), d_e7med=d("E7-med"), d_c2=d("C2"),
                reg_e7med=reg["E7-med"], reg_c2=reg["C2"], reg_lgbq=reg["lgb_quantile"])


def main():
    rows = []
    for d in ("M5", "VN1"):
        for wname, off in WINDOWS.items():
            w = load_window(d, off)
            p, idx, test0, T, D = w["p"], w["idx"], w["test0"], w["T"], w["D"]
            Y = p["Y"].astype(np.float64)
            start = p["start"].astype(int)
            t = np.arange(T)[None, :]
            hist = (t >= start[:, None]) & (t < test0)
            Yh = np.nan_to_num(Y) * hist
            rate = (Yh.sum(1) / np.maximum(hist.sum(1), 1))[idx]
            pos = (Yh.sum(1) / np.maximum((Yh > 0).sum(1), 1))[idx]
            rows.append(dict(dataset=d, window=wname, alpha=np.nan, rule="base", flagged=0.0, **summarise(need_table(D, w["Q"]))))
            for a in ALPHAS:
                F, _ = flag_weeks(Y, start, test0, a)
                Ft = F[idx][:, test0:T]
                for rule in RULES:
                    fill = {"mean": rate, "half": rate / 2, "pos": pos}[rule][:, None]
                    Dimp = np.where(Ft, np.maximum(D, fill), D)
                    rows.append(dict(dataset=d, window=wname, alpha=a, rule=rule, flagged=Ft.mean(),
                                     **summarise(need_table(Dimp, w["Q"]))))
                print(d, wname, "alpha", a, "done", flush=True)
    res = pd.DataFrame(rows)
    out = os.path.join(config.OUTPUTS, "censoring")
    res.to_csv(os.path.join(out, "censoring_sensitivity.csv"), index=False)
    pc = lambda v: f"{100 * v:+.1f}"
    L = ["# Censoring sensitivity: detector threshold × imputation rule (generated by code/censoring_sensitivity.py)", "",
         "Δ at fill 0.92 vs LGB-Q (%, range over the three windows); regret = maximum over the six runs (%). "
         "leaders = leading single method per run (M5 main/second/third; VN1 main/second/third).", "",
         "| α | rule | flagged test weeks M5 / VN1 | leaders | Δ TSB-NB M5 | Δ E7-med M5 | Δ E7-med VN1 | max regret E7-med | C2 | LGB-Q |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for (a, rule), g in res.groupby(["alpha", "rule"], dropna=False, sort=False):
        m5, vn = g[g.dataset == "M5"], g[g.dataset == "VN1"]
        rng = lambda s: f"{pc(s.min())} to {pc(s.max())}"
        L.append(f"| {'—' if not np.isfinite(a) else a} | {rule} | {100 * m5.flagged.mean():.1f}% / {100 * vn.flagged.mean():.1f}% | "
                 f"{', '.join(m5.leader)}; {', '.join(vn.leader)} | {rng(m5.d_tsb)} | {rng(m5.d_e7med)} | {rng(vn.d_e7med)} | "
                 f"{100 * g.reg_e7med.max():.1f} | {100 * g.reg_c2.max():.1f} | {100 * g.reg_lgbq.max():.1f} |")
    with open(os.path.join(out, "censoring_sensitivity.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("written", os.path.join(out, "censoring_sensitivity.md"))


if __name__ == "__main__":
    main()
