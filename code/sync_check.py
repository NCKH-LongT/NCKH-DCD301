"""B1 — check that M5 and VN1 are prepared in the same way, and quantify the one known asymmetry.

Checks, per dataset (main test window unless stated):
    panel shape, week length and weekday of the week start, test-period dates
    series-start definition; missing / negative values after the start
    price availability; features of the ML models (shared vs dataset-specific)
    series selection rule and number of evaluated series in the three test windows
Asymmetry: M5 series start at the first week with a listed price, VN1 series at the first sale. The script
recomputes the M5 statistics with the VN1 definition (start = first sale) to show how much it matters.
Writes code/outputs/sync_check.md and sync_check.csv.

Usage:
    python code/sync_check.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import classify, config, data  # noqa: E402
from f2d.features import Builder  # noqa: E402

OFFSETS = (0, 26, 52)


def first_sale(Y):
    Y0 = np.nan_to_num(Y)
    return np.where((Y0 > 0).any(1), (Y0 > 0).argmax(1), Y.shape[1]).astype(np.int32)


def stats(p, start, cutoff):
    """Zero share, class shares and number of evaluated series for a given start definition."""
    Y = np.nan_to_num(p["Y"]).copy()
    t = np.arange(Y.shape[1])[None, :]
    Ym = np.where(t >= start[:, None], Y, np.nan)
    sel = start <= cutoff - config.VALID_WEEKS
    cls, adi, _ = classify.classify(Ym, start, cutoff)
    sel &= cls != "none"
    act = (t >= start[:, None]) & (t < cutoff)
    zero = 1 - ((Y > 0) & act)[sel].sum() / act[sel].sum()
    shares = {c: float((cls[sel] == c).mean()) for c in classify.CLASSES}
    return dict(n_eval=int(sel.sum()), zero_share=float(zero), median_adi=float(np.nanmedian(adi[sel])),
                median_hist=float(np.median((cutoff - start)[sel])), **shares), sel


def main():
    rows, lines = [], ["# B1 — Synchronisation check of M5 and VN1 (generated by code/sync_check.py)", ""]
    P = {d: data.load(d) for d in ("M5", "VN1")}
    info = {}
    for d, p in P.items():
        Y = p["Y"]
        n, T = Y.shape
        weeks = pd.DatetimeIndex(p["weeks"])
        gaps = np.unique(np.diff(weeks.values).astype("timedelta64[D]").astype(int))
        t = np.arange(T)[None, :]
        after = t >= p["start"][:, None]
        fs = first_sale(Y)
        b = Builder(p)
        info[d] = dict(
            series=n, weeks=T, first_week=str(weeks[0].date()), last_week=str(weeks[-1].date()),
            week_gap_days=",".join(map(str, gaps)), week_start_day=weeks[0].day_name(),
            nan_after_start=int(np.isnan(Y[after]).sum()), negative=int((np.nan_to_num(Y) < 0).sum()),
            start_equals_first_sale=float(np.mean(p["start"] == fs)),
            median_weeks_listed_before_first_sale=float(np.median((fs - p["start"])[fs < T])),
            series_never_sold=int((fs >= T).sum()),
            price_cells_observed=float(p["Pobs"][after].mean()),
            price_cells_after_ffill=float(np.isfinite(p["P"][after]).mean()),
            n_features=len(b.names), features=b.names)
    shared = [f for f in info["M5"]["features"] if f in info["VN1"]["features"]]
    only = {d: [f for f in info[d]["features"] if f not in shared] for d in info}

    def row(crit, m5, vn1, same, note):
        rows.append(dict(criterion=crit, M5=m5, VN1=vn1, status="same" if same else "DIFFERENT", handling=note))

    a, v = info["M5"], info["VN1"]
    row("Series × weeks in the panel", f"{a['series']:,} × {a['weeks']}", f"{v['series']:,} × {v['weeks']}", False,
        "Different sizes by nature; all KPIs are ratios and all tests are per dataset")
    row("Week length (days between week starts)", a["week_gap_days"], v["week_gap_days"], a["week_gap_days"] == v["week_gap_days"],
        "Both panels are regular 7-day weeks")
    row("Weekday of the week start", a["week_start_day"], v["week_start_day"], a["week_start_day"] == v["week_start_day"],
        "No effect: the two panels are never joined on time")
    row("Calendar period", f"{a['first_week']} → {a['last_week']}", f"{v['first_week']} → {v['last_week']}", False,
        "Different years; each dataset has its own three test windows")
    row("Missing sales after the series start", a["nan_after_start"], v["nan_after_start"], a["nan_after_start"] == v["nan_after_start"], "—")
    row("Negative sales", a["negative"], v["negative"], a["negative"] == v["negative"], "—")
    row("Series-start definition", "first week with a listed price", "first week with a sale", False,
        "ASYMMETRY — quantified below (M5 recomputed with the VN1 definition)")
    row("Share of series whose start equals the first sale", f"{a['start_equals_first_sale']:.1%}", f"{v['start_equals_first_sale']:.1%}", False,
        f"M5: median {a['median_weeks_listed_before_first_sale']:.0f} listed weeks before the first sale")
    row("Price cells observed after the start", f"{a['price_cells_observed']:.1%}", f"{v['price_cells_observed']:.1%}", False,
        "VN1 prices exist only in weeks with sales and not in Phase 2; carried forward; price ablation in B0")
    row("Price cells after carry-forward", f"{a['price_cells_after_ffill']:.1%}", f"{v['price_cells_after_ffill']:.1%}",
        abs(a["price_cells_after_ffill"] - v["price_cells_after_ffill"]) < 0.005, "—")
    row("Model features", a["n_features"], v["n_features"], False,
        f"{len(shared)} shared; M5 only: {', '.join(only['M5'])}; VN1 only: {', '.join(only['VN1']) or 'none'}")
    row("Series selection rule", "start ≤ test start − 13 weeks, ≥ 1 sale before the test", "same", True, "Same code path (run_pipeline.py)")
    row("Split / retraining / validation", "26 test weeks, 2 blocks of 13, 13 validation origins", "same", True, "Same code path (config.py)")
    row("Demand unit", "product × store", "client × warehouse × product", False, "Different aggregation level by nature; stated in the paper")

    lines += ["## 1. Checklist", "", pd.DataFrame(rows).to_markdown(index=False), ""]

    # ---- asymmetry: M5 with the VN1 start definition, three windows
    lines += ["## 2. Effect of the series-start definition", "",
              "M5 statistics with its own definition (first listed price) and with the VN1 definition (first sale). "
              "VN1 cannot be recomputed with the M5 definition because it has no listing information.", ""]
    comp = []
    for off in OFFSETS:
        for d, p in P.items():
            T = p["Y"].shape[1] - off
            cutoff = T - config.TEST_WEEKS
            q = data.truncate(p, T) if off else p
            defs = {"own definition": q["start"]}
            if d == "M5":
                defs["first sale (VN1 definition)"] = np.minimum(first_sale(q["Y"]), T)
            for name, st in defs.items():
                s, _ = stats(q, st.astype(np.int32), cutoff)
                comp.append(dict(dataset=d, window=f"w{off}" if off else "main", start=name, **s))
    comp = pd.DataFrame(comp)
    comp.to_csv(os.path.join(config.OUTPUTS, "sync_check.csv"), index=False)
    show = comp.copy()
    for c in ["zero_share", *classify.CLASSES]:
        show[c] = (100 * show[c]).round(1)
    show["median_adi"] = show["median_adi"].round(2)
    lines += [show.to_markdown(index=False), "",
              "zero_share and class columns in %; classes computed on the history before the test period.", ""]
    with open(os.path.join(config.OUTPUTS, "sync_check.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("written code/outputs/sync_check.md")


if __name__ == "__main__":
    main()
