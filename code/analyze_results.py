"""Cross-dataset analysis of run_pipeline.py outputs (RQ1–RQ4).

Reads code/outputs/<DATASET>/{kpi,forecast_metrics}.csv and writes
    code/outputs/comparison.md          tables used in the paper draft
    code/outputs/fig_tradeoff_<D>.png   inventory (weeks of demand) vs fill rate as τ varies

Usage:
    python code/analyze_results.py
"""
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import config  # noqa: E402

D = config.DEFAULT
DATASETS = [d for d in ("M5", "VN1") if os.path.exists(os.path.join(config.OUTPUTS, d, "kpi.csv"))]
CLASSES = ["all", "smooth", "erratic", "intermittent", "lumpy"]


def load(d):
    k = pd.read_csv(os.path.join(config.OUTPUTS, d, "kpi.csv"))
    f = pd.read_csv(os.path.join(config.OUTPUTS, d, "forecast_metrics.csv"))
    return k, f


def is_base(k, **over):
    s = {"tau": D["tau"], "L": D["L"], "H": D["H"], "q_liq": D["q_liq"], "k": D["k_fixed"], **over}
    m = np.ones(len(k), bool)
    for c, v in s.items():
        m &= k[c].to_numpy() == v
    return m


def main():
    lines = ["# Cross-dataset results (generated by code/analyze_results.py)", ""]
    ranks = {}
    for d in DATASETS:
        k, f = load(d)
        lines += [f"## {d}", ""]

        # 1. forecast accuracy at h = L+R and H
        h_lr = D["L"] + D["R"]
        t = f[(f.group == "all") & f.horizon.isin([h_lr, D["H"]])][["model", "horizon", "SQL", "RMSSE", "cov_0.8", "cov_0.9", "cov_0.95"]]
        lines += ["### Forecast accuracy (all series)", "", t.round(3).to_markdown(index=False), ""]
        t = f[f.horizon == h_lr].pivot(index="model", columns="group", values="SQL")[CLASSES]
        lines += [f"### SQL by demand class (h = {h_lr})", "", t.round(3).to_markdown(), ""]

        # 2. default scenario, no liquidation
        base = k[is_base(k) & (k.policy == "none")]
        cols = ["model", "fill_rate", "stockout_rate_demand_weeks", "inventory_weeks", "excess_weeks_of_demand"]
        cols += [c for c in ("fill_rate_lo", "fill_rate_hi", "inventory_weeks_lo", "inventory_weeks_hi") if c in k.columns]
        lines += ["### Inventory KPIs, default scenario, no liquidation (all series)", "",
                  base[base.group == "all"][cols].round(3).to_markdown(index=False), ""]
        for kpi_name in ("fill_rate", "inventory_weeks"):
            t = base.pivot(index="model", columns="group", values=kpi_name)[CLASSES]
            lines += [f"### {kpi_name} by demand class (default, no liquidation)", "", t.round(3).to_markdown(), ""]

        # 3. trade-off across τ (needs --grid full)
        tr = k[(k.policy == "none") & (k.group == "all") & (k.L == D["L"]) & (k.H == D["H"])
               & (k.q_liq == D["q_liq"]) & (k.k == D["k_fixed"])]
        if tr.tau.nunique() > 1:
            t = tr.pivot(index="model", columns="tau", values=["fill_rate", "inventory_weeks"])
            lines += ["### Trade-off: fill rate and inventory (weeks) across target service level τ", "",
                      t.round(3).to_markdown(), ""]
            fig, ax = plt.subplots(figsize=(5.5, 4))
            for m, g in tr.groupby("model"):
                g = g.sort_values("tau")
                ax.plot(g.inventory_weeks, g.fill_rate, marker="o", label=m)
            ax.set_xlabel("Average inventory (weeks of demand)")
            ax.set_ylabel("Fill rate")
            ax.set_title(f"{d}: inventory–fill-rate trade-off (τ = 0.80, 0.90, 0.95)")
            ax.grid(alpha=.3); ax.legend(fontsize=8)
            fig.tight_layout(); fig.savefig(os.path.join(config.OUTPUTS, f"fig_tradeoff_{d}.png"), dpi=150)
            plt.close(fig)
            lines += [f"![trade-off](fig_tradeoff_{d}.png)", ""]

        # 4. liquidation (default scenario)
        liq = k[is_base(k) & (k.group == "all")][["model", "policy", "fill_rate", "stockout_rate_demand_weeks", "inventory_weeks",
                                                  "excess_weeks_of_demand", "liquidated_share", "liq_series_share"]]
        lines += ["### Liquidation policies, default scenario (all series)", "", liq.round(4).to_markdown(index=False), ""]

        # 5. sensitivity (L, H) for the main model
        sens = k[(k.group == "all") & (k.model == "lgb_quantile")]
        if sens.L.nunique() > 1 or sens.H.nunique() > 1:
            t = sens[(sens.tau == D["tau"])][["policy", "L", "H", "q_liq", "k", "fill_rate", "inventory_weeks", "liquidated_share"]]
            lines += ["### Scenario sensitivity, lgb_quantile (τ = 0.9)", "", t.round(3).to_markdown(index=False), ""]

        ranks[d] = base[base.group.isin(CLASSES)].set_index(["group", "model"])["fill_rate"]

    # 6. ranking consistency between datasets (fill rate at the default scenario, by class)
    if len(ranks) == 2:
        a, b = ranks["M5"], ranks["VN1"]
        lines += ["## Ranking consistency M5 vs VN1 (Spearman ρ of fill-rate ranks across models)", "",
                  "| group | ρ | models |", "|---|---|---|"]
        for g in CLASSES:
            x, y = a.loc[g], b.loc[g]
            common = x.index.intersection(y.index)
            rho = stats.spearmanr(x[common], y[common]).statistic if len(common) > 2 else np.nan
            lines.append(f"| {g} | {rho:.2f} | {len(common)} |")
        lines.append("")

    with open(os.path.join(config.OUTPUTS, "comparison.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
