"""P0-1: τ chosen on the previous window, applied unchanged to the next (design: phase5_workflow.md, section 8).

For each method, τ* is found by bisection on [0.5, 0.99] so that the realised fill rate in the source window equals the
target (0.92, 0.94); the order-up-to level for a continuous τ interpolates linearly between the cached quantiles.
τ* is then used in the next window (third → second, second → main). Reported per target window: τ*, achieved fill,
inventory (weeks of demand), differences to LGB-Q, and the ex-post inventory at equal fill in the same window for
comparison. Writes code/outputs/robustness/prospective_tau.md and .csv.

Usage:
    python code/prospective_tau.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import config  # noqa: E402
from robust_common import LAB, METHODS, WINDOWS, level, load_window, run  # noqa: E402
from segment_eval import inv_at  # noqa: E402

TARGETS = (0.92, 0.94)
TRANSITIONS = [("third", "second"), ("second", "main")]


def fill_inv(D, Qm, tau):
    s, o = run(D, level(Qm, tau))
    dem = D[:, config.WARMUP_WEEKS:].sum()
    return s.sum() / dem, o.sum() / dem


def solve_tau(D, Qm, target, iters=14):
    lo, hi = 0.5, 0.99
    if fill_inv(D, Qm, hi)[0] < target:
        return hi, False
    if fill_inv(D, Qm, lo)[0] >= target:
        return lo, True
    for _ in range(iters):
        mid = (lo + hi) / 2
        if fill_inv(D, Qm, mid)[0] < target:
            lo = mid
        else:
            hi = mid
    return hi, True


def main():
    out = os.path.join(config.OUTPUTS, "robustness")
    os.makedirs(out, exist_ok=True)
    rows = []
    for d in ("M5", "VN1"):
        W = {w: load_window(d, off) for w, off in WINDOWS.items()}
        for src, dst in TRANSITIONS:
            for target in TARGETS:
                res = {}
                for m in METHODS:
                    tau, ok = solve_tau(W[src]["D"], W[src]["Q"][m], target)
                    f, i = fill_inv(W[dst]["D"], W[dst]["Q"][m], tau)
                    # ex-post: inventory at the same realised fill in the target window (curve over the τ grid)
                    fs, iv = zip(*[fill_inv(W[dst]["D"], W[dst]["Q"][m], t) for t in config.TAU_GRID])
                    res[m] = dict(tau=tau, reached=ok, fill=f, inv=i,
                                  expost=inv_at(np.maximum.accumulate(np.array(fs)), np.array(iv), target))
                ref = res["lgb_quantile"]
                for m in METHODS:
                    r = res[m]
                    rows.append(dict(dataset=d, transition=f"{src} → {dst}", target=target, method=LAB[m], tau=r["tau"],
                                     reached_in_source=r["reached"], fill=r["fill"], inv=r["inv"],
                                     d_fill_vs_lgbq=r["fill"] - ref["fill"], d_inv_vs_lgbq=r["inv"] / ref["inv"] - 1,
                                     expost_d_inv_vs_lgbq=(r["expost"] / ref["expost"] - 1
                                                           if np.isfinite(r["expost"]) and np.isfinite(ref["expost"]) else np.nan)))
                print(d, src, "->", dst, target, "done", flush=True)
    res = pd.DataFrame(rows)
    res.to_csv(os.path.join(out, "prospective_tau.csv"), index=False)
    L = ["# τ chosen on the previous window and applied to the next (generated by code/prospective_tau.py)", "",
         "Design fixed beforehand: 07_paper_draft/phase5_workflow.md, section 8. fill = realised fill in the target window; "
         "inv = inventory in weeks of demand; Δ vs LGB-Q (fill in points, inventory in %). 'ex-post Δ inv' = inventory at "
         "equal realised fill in the target window (the paper's metric), for comparison.", ""]
    for (d, tr, tg), g in res.groupby(["dataset", "transition", "target"], sort=False):
        L += [f"## {d} · {tr} · target fill {tg}", "",
              "| method | τ* | fill | |fill − target| | inv | Δ fill vs LGB-Q | Δ inv vs LGB-Q | ex-post Δ inv |", "|---|---|---|---|---|---|---|---|"]
        for _, r in g.iterrows():
            L.append(f"| {r.method} | {r.tau:.3f}{'' if r.reached_in_source else ' (max)'} | {r.fill:.3f} | {abs(r.fill - tg):.3f} | "
                     f"{r.inv:.2f} | {100 * r.d_fill_vs_lgbq:+.1f} pt | {100 * r.d_inv_vs_lgbq:+.1f}% | "
                     f"{'—' if not np.isfinite(r.expost_d_inv_vs_lgbq) else f'{100 * r.expost_d_inv_vs_lgbq:+.1f}%'} |")
        L.append("")
    with open(os.path.join(out, "prospective_tau.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("written", os.path.join(out, "prospective_tau.md"))


if __name__ == "__main__":
    main()
