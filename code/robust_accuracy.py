"""Robust summaries of forecast accuracy (reviewer point B1: the mean SQL is unstable on VN1).

For every dataset × test window × horizon × demand class × method, from the cached forecasts:
    mean_SQL      mean over series of the per-series scaled quantile loss (as in evaluate.forecast_metrics)
    median_SQL    median over series of the same per-series loss
    trim_SQL      mean after dropping the 1% of series with the largest per-series loss of that method
    wQL           volume-weighted quantile loss: Σ pinball over series, origins and quantiles
                  / (n_quantiles · Σ D_h over series and origins); needs no per-series scale
    max_SQL       largest per-series loss (shows what drives the mean)
Writes code/outputs/robust_accuracy.csv and robust_accuracy.md.

Usage:
    python code/robust_accuracy.py
    python code/robust_accuracy.py --runs VN1:0,VN1:26,VN1:52
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import classify, config, data, evaluate  # noqa: E402
from f2d.features import Builder  # noqa: E402

MODELS = ["empirical", "tsb", "tsb_nb", "ets", "lgb_tweedie", "lgb_conformal", "hgb_quantile", "lgb_quantile"]
CLASSES = ["all", "smooth", "erratic", "intermittent", "lumpy"]
TRIM = 0.01


def run(name, offset):
    p = data.load(name)
    if offset:
        p = data.truncate(p, p["Y"].shape[1] - offset)
    Y = p["Y"]
    T = Y.shape[1]
    test0 = T - config.TEST_WEEKS
    origins = list(range(test0, T))
    sel = p["start"] <= test0 - config.VALID_WEEKS
    cls, _, _ = classify.classify(Y, p["start"], test0)
    sel &= cls != "none"
    idx = np.flatnonzero(sel)
    s_abs, _ = evaluate.naive_scales(Y, p["start"], test0)
    b = Builder(p)
    qs = np.asarray(config.QUANTILES)
    fc = os.path.join(config.CACHE, "forecasts", name + (f"_w{offset}" if offset else ""))
    c = cls[idx]
    rows = []
    for h in (config.DEFAULT["L"] + config.DEFAULT["R"], config.DEFAULT["H"]):
        Dt = np.stack([b.target(o, h) for o in origins], 1)
        for m in MODELS:
            Q = np.load(os.path.join(fc, f"{m}_h{h}.npz"))["Q"]
            e = Dt[:, :, None] - Q
            ok = ~np.isnan(Dt)[:, :, None] & ~np.isnan(Q)
            pin = np.where(ok, np.maximum(qs * e, (qs - 1) * e), np.nan)
            with np.errstate(all="ignore"):
                sql = np.nanmean(pin, axis=(1, 2)) / (h * s_abs)
            sql = np.where((s_abs > 0) & np.isfinite(sql), sql, np.nan)[idx]
            pin_sum = np.nansum(pin, axis=(1, 2))[idx]                       # Σ over origins and quantiles
            d_sum = np.nansum(np.where(ok.any(2), Dt, np.nan), axis=1)[idx]  # Σ D_h over the scored origins
            for g in CLASSES:
                mask = np.ones(len(c), bool) if g == "all" else c == g
                v = sql[mask]
                v = v[np.isfinite(v)]
                k = int(np.ceil(TRIM * len(v)))
                vt = np.sort(v)[: len(v) - k] if k else v
                rows.append(dict(dataset=name, window=f"w{offset}" if offset else "main", h=h, group=g, model=m,
                                 n_series=len(v), mean_SQL=v.mean(), median_SQL=np.median(v), trim_SQL=vt.mean(),
                                 wQL=pin_sum[mask].sum() / (len(qs) * d_sum[mask].sum()), max_SQL=v.max()))
    return pd.DataFrame(rows)


def main():
    global MODELS
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="M5:0,M5:26,M5:52,VN1:0,VN1:26,VN1:52", help="dataset:offset pairs")
    ap.add_argument("--models", default=",".join(MODELS))
    ap.add_argument("--out-suffix", default="")
    a = ap.parse_args()
    MODELS = a.models.split(",")
    osfx = f"_{a.out_suffix}" if a.out_suffix else ""
    out = pd.concat([run(r.split(":")[0], int(r.split(":")[1])) for r in a.runs.split(",")], ignore_index=True)
    out.to_csv(os.path.join(config.OUTPUTS, f"robust_accuracy{osfx}.csv"), index=False)
    lines = ["# Robust accuracy summaries (generated by code/robust_accuracy.py)", "",
             "mean / median / 1%-trimmed mean of the per-series SQL, and the volume-weighted quantile loss wQL "
             "(Σ pinball / (n_q · Σ D_h)). All series; lower is better.", ""]
    for (d, w, h), g in out[out.group == "all"].groupby(["dataset", "window", "h"], sort=False):
        t = g.set_index("model")[["mean_SQL", "median_SQL", "trim_SQL", "wQL", "max_SQL"]]
        t["rank_mean"] = t.mean_SQL.rank()
        t["rank_median"] = t.median_SQL.rank()
        t["rank_wQL"] = t.wQL.rank()
        lines += [f"## {d}, window {w}, h = {h} (n = {int(g.n_series.iloc[0]):,})", "", t.round(3).to_markdown(), ""]
    lines += ["## Best method by metric and demand class (h = L+R)", ""]
    h0 = config.DEFAULT["L"] + config.DEFAULT["R"]
    best = []
    for (d, w, grp), g in out[out.h == h0].groupby(["dataset", "window", "group"], sort=False):
        g = g.set_index("model")
        best.append(dict(dataset=d, window=w, group=grp, best_mean=g.mean_SQL.idxmin(), best_median=g.median_SQL.idxmin(),
                         best_trim=g.trim_SQL.idxmin(), best_wQL=g.wQL.idxmin()))
    lines += [pd.DataFrame(best).to_markdown(index=False), ""]
    with open(os.path.join(config.OUTPUTS, f"robust_accuracy{osfx}.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"written code/outputs/robust_accuracy{osfx}.md")


if __name__ == "__main__":
    main()
