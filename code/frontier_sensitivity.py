"""Sensitivity of the frontier rank to the set of fill-rate targets (reviewer point B7).

The frontier rank of analyze_results.py averages the rank of the inventory needed over the targets
0.90, 0.92, 0.94, 0.96, 0.98. Here the same computation is repeated for other target sets, and a second,
rank-free summary is added:
    excess   mean over the targets reached by the method of (I_method / I_best − 1), where I_best is the smallest
             inventory among the methods that reach the target; n_reached = number of targets the method reaches.
Reads code/outputs/<DATASET>[_w26|_w52]/kpi.csv; writes code/outputs/frontier_sensitivity.csv and .md.

Usage:
    python code/frontier_sensitivity.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_results import frontier_rank  # noqa: E402
from f2d import config  # noqa: E402

D = config.DEFAULT
SETS = {
    "paper (0.90–0.98, step 0.02)": (0.90, 0.92, 0.94, 0.96, 0.98),
    "moderate (0.90–0.94)": (0.90, 0.92, 0.94),
    "high (0.94–0.98)": (0.94, 0.96, 0.98),
    "fine (0.88–0.98, step 0.01)": tuple(np.round(np.arange(0.88, 0.981, 0.01), 2)),
}
RUNS = [("M5", ""), ("M5", "_w26"), ("M5", "_w52"), ("VN1", ""), ("VN1", "_w26"), ("VN1", "_w52")]
CLASSES = ["all", "smooth", "erratic", "intermittent", "lumpy"]


def needed(k, group, targets):
    tg = k[(k.policy == "none") & (k.group == group) & (k.L == D["L"]) & (k.H == D["H"])
           & (k.q_liq == D["q_liq"]) & (k.k == D["k_fixed"])]
    rows = {}
    for m, gg in tg.groupby("model"):
        gg = gg.sort_values("tau")
        f_ = np.maximum.accumulate(gg.fill_rate.to_numpy())
        i_ = gg.inventory_weeks.to_numpy()
        rows[m] = {t: (np.interp(t, f_, i_) if f_.min() <= t <= f_.max() else np.nan) for t in targets}
    return pd.DataFrame(rows).T


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--exclude", default="", help="comma-separated methods to leave out, e.g. tsb")
    ap.add_argument("--out-suffix", default="")
    a = ap.parse_args()
    excl = [m for m in a.exclude.split(",") if m]
    osfx = f"_{a.out_suffix}" if a.out_suffix else ""
    out = []
    for d, sfx in RUNS:
        path = os.path.join(config.OUTPUTS, d + sfx, "kpi.csv")
        if not os.path.exists(path):
            continue
        k = pd.read_csv(path)
        k = k[~k.model.isin(excl)]
        for g in CLASSES:
            for name, targets in SETS.items():
                t = needed(k, g, targets)
                fr = frontier_rank(t)
                best = t.min(0)
                rel = t.div(best, axis=1) - 1
                for m in t.index:
                    out.append(dict(dataset=d, window=sfx.strip("_") or "main", group=g, target_set=name, model=m,
                                    frontier_rank=fr.get(m, np.nan), excess=rel.loc[m].mean(),
                                    n_reached=int(t.loc[m].notna().sum()), n_targets=len(targets)))
    out = pd.DataFrame(out)
    out.to_csv(os.path.join(config.OUTPUTS, f"frontier_sensitivity{osfx}.csv"), index=False)

    lines = ["# Sensitivity of the frontier rank to the fill-rate targets (generated by code/frontier_sensitivity.py)", "",
             "Leader = method with the best (lowest) frontier rank; in brackets its rank, then the runner-up.", ""]
    for g in CLASSES:
        lines += [f"## {g}", "", "| dataset | window | " + " | ".join(SETS) + " |", "|---|---|" + "---|" * len(SETS)]
        for d, sfx in RUNS:
            w = sfx.strip("_") or "main"
            cells = []
            for name in SETS:
                s = out[(out.dataset == d) & (out.window == w) & (out.group == g) & (out.target_set == name)]
                s = s.dropna(subset=["frontier_rank"]).sort_values("frontier_rank")
                if s.empty:
                    cells.append("n/a")
                else:
                    a, b = s.iloc[0], s.iloc[1]
                    cells.append(f"{a.model} ({a.frontier_rank:.2f}); {b.model} ({b.frontier_rank:.2f})")
            lines.append(f"| {d} | {w} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["## Mean excess inventory over the best method, all series, paper target set",
              "", "excess = mean of I_method / I_best − 1 over the targets the method reaches; (n) = targets reached out of 5.", ""]
    s = out[(out.group == "all") & (out.target_set == list(SETS)[0])].copy()
    s["cell"] = [f"{100 * e:.1f}% ({n})" if np.isfinite(e) else "—" for e, n in zip(s.excess, s.n_reached)]
    s["col"] = s.dataset + " " + s.window
    lines += [s.pivot(index="model", columns="col", values="cell")[[f"{d} {x.strip('_') or 'main'}" for d, x in RUNS]].to_markdown(), ""]
    with open(os.path.join(config.OUTPUTS, f"frontier_sensitivity{osfx}.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"written code/outputs/frontier_sensitivity{osfx}.md")


if __name__ == "__main__":
    main()
