"""Inventory–service trade-off of Table 7 (design: phase5_workflow.md, section 10, item 4).

Reads the full-policy bootstrap (full_policy_bootstrap.py). For each case × method (vs LGB-Q):
    target met     |achieved fill − 0.92| < 0.005 for the method (and for LGB-Q, reported separately)
    comparable     |Δ fill vs LGB-Q| < threshold, threshold ∈ {0.25, 0.5, 1.0} points; also the share of bootstrap
                   replicates in which the fills are that close
    verdict        among comparable cases: significant saving (ΔI interval below 0), significantly more stock (above
                   0) or inconclusive; non-comparable cases get no inventory verdict
Writes code/outputs/robustness/service_tradeoff.{md,csv}.

Usage:
    python code/service_tradeoff.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import config  # noqa: E402

TARGET = 0.92
THRESHOLDS = (0.0025, 0.005, 0.01)


def main():
    out = os.path.join(config.OUTPUTS, "robustness")
    res = pd.read_csv(os.path.join(out, "full_policy_bootstrap.csv"))
    reps = pd.read_csv(os.path.join(out, "full_policy_bootstrap_reps.csv.gz"))
    rows = []
    for (d, tr), g in res.groupby(["dataset", "transition"], sort=False):
        rg = reps[(reps.dataset == d) & (reps.transition == tr)]
        ref = rg[rg.method == "LGB-Q"].set_index("rep").fill
        lq = g[g.method == "LGB-Q"].iloc[0]
        for _, r in g[g.method != "LGB-Q"].iterrows():
            dfb = (rg[rg.method == r.method].set_index("rep").fill - ref).loc[1:]
            row = dict(dataset=d, transition=tr, method=r.method, fill=r.fill, lgbq_fill=lq.fill,
                       method_target_met=abs(r.fill - TARGET) < 0.005, lgbq_target_met=abs(lq.fill - TARGET) < 0.005,
                       d_fill=r.d_fill, d_inv=r.d_inv, dinv_lo=r.dinv_lo, dinv_hi=r.dinv_hi)
            for thr in THRESHOLDS:
                comp = abs(r.d_fill) < thr
                row[f"comparable_{thr}"] = comp
                row[f"p_close_{thr}"] = float((dfb.abs() < thr).mean())
                row[f"verdict_{thr}"] = ("not comparable" if not comp else "saving" if r.dinv_hi < 0
                                         else "more stock" if r.dinv_lo > 0 else "inconclusive")
            rows.append(row)
    t = pd.DataFrame(rows)
    t.to_csv(os.path.join(out, "service_tradeoff.csv"), index=False)
    pc = lambda v: f"{100 * v:+.1f}"
    L = ["# Inventory–service trade-off of Table 7 (generated by code/service_tradeoff.py)", "",
         f"Target fill {TARGET}. Inventory verdicts use the full-policy bootstrap intervals and are given only where the "
         "achieved fills are comparable. p(close) = share of bootstrap replicates in which the two fills are within the "
         "threshold.", "", "## Counts by fill-equivalence threshold", "",
         "| threshold (points) | comparable | saving | more stock | inconclusive | not comparable |", "|---|---|---|---|---|---|"]
    for thr in THRESHOLDS:
        v = t[f"verdict_{thr}"].value_counts()
        L.append(f"| {100 * thr:.2f} | {int(t[f'comparable_{thr}'].sum())} of {len(t)} | {v.get('saving', 0)} | "
                 f"{v.get('more stock', 0)} | {v.get('inconclusive', 0)} | {v.get('not comparable', 0)} |")
    L += ["", "## Target attainment (|achieved fill − 0.92| < 0.5 points)", "",
          f"LGB-Q meets the target in {int(t.drop_duplicates(['dataset', 'transition']).lgbq_target_met.sum())} of 5 cases; "
          f"the other methods in {int(t.method_target_met.sum())} of {len(t)} method–case pairs.", "",
          "## Case by case (threshold 0.5 points)", "",
          "| case | method | fill | LGB-Q fill | Δ fill pt | p(close) | ΔI % [CI] | verdict |", "|---|---|---|---|---|---|---|---|"]
    for _, r in t.iterrows():
        L.append(f"| {r.dataset} {r.transition} | {r.method} | {r.fill:.3f} | {r.lgbq_fill:.3f} | {pc(r.d_fill)} | "
                 f"{100 * r['p_close_0.005']:.0f}% | {pc(r.d_inv)} [{pc(r.dinv_lo)}, {pc(r.dinv_hi)}] | {r['verdict_0.005']} |")
    with open(os.path.join(out, "service_tradeoff.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("written service_tradeoff.md")


if __name__ == "__main__":
    main()
