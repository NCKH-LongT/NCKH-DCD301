"""Cost view of the trade-off curves (Theodorou et al. 2025: cost-based and cost-free conclusions can disagree).

Per unit of demand over the KPI weeks, with unit cost c, weekly holding rate hw (annual rate / 52) and a lost-sales
penalty b per unit (both as fractions of c), the cost of a policy is
    c · ( hw · inventory_weeks + b · (1 − fill_rate) ).
Dividing by c · hw gives a cost in "weeks of holding": C(r) = inventory_weeks + r · (1 − fill_rate), with the single
ratio r = b / hw. Each method may choose its best service level, so its cost is the minimum of C(r) over its
trade-off curve (the curve is piecewise linear, hence the minimum lies on one of the τ grid points).
The ratio r spans 10 to 1,000; e.g. a 20% annual holding rate (hw ≈ 0.0038) with a lost margin of 30% gives
r ≈ 78, and the cost parameters of Theodorou et al. (annual holding 1%, lost sales 12.5% of the price) give r ≈ 650.
Reported per dataset × window × r: cost of every method relative to the cheapest single method (regret), the
cheapest method, and the maximum regret over the six runs. Seven single methods plus the combination C2.
Writes code/outputs/cost_view.md and .csv.

Usage:
    python code/cost_view.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from combination import WINDOWS, add_combos, setup  # noqa: E402
from equal_fill_ci import totals  # noqa: E402
from f2d import config  # noqa: E402
from segment_eval import MODELS  # noqa: E402

RATIOS = (10, 20, 50, 100, 200, 500, 1000)
LAB = {"empirical": "EMP", "tsb_nb": "TSB-NB", "ets": "ETS", "lgb_tweedie": "LGB-T", "lgb_conformal": "LGB-C",
       "hgb_quantile": "HGB-Q", "lgb_quantile": "LGB-Q", "C2": "C2", "C3": "C3"}


def main():
    rows = []
    for d in ("M5", "VN1"):
        for wname, off in WINDOWS.items():
            p, idx, test0, T = setup(d, off)
            tot = totals(d, off, MODELS)
            add_combos(tot, p, d, off, idx, test0, T)
            dem = tot["demand"].sum()
            for m in MODELS + ["C2"]:
                fill = np.array([tot[m, t, "sales"].sum() / dem for t in config.TAU_GRID])
                inv = np.array([tot[m, t, "onhand"].sum() / dem for t in config.TAU_GRID])
                for r in RATIOS:
                    c = inv + r * (1 - fill)
                    k = int(np.argmin(c))
                    rows.append(dict(dataset=d, window=wname, method=LAB[m], ratio=r, cost=c[k],
                                     tau=config.TAU_GRID[k], fill=fill[k], inventory=inv[k]))
            print(d, wname, "done", flush=True)
    res = pd.DataFrame(rows)
    single = res[res.method != "C2"]
    best = single.groupby(["dataset", "window", "ratio"]).cost.min().rename("best")
    res = res.join(best, on=["dataset", "window", "ratio"])
    res["regret"] = res.cost / res.best - 1
    res.to_csv(os.path.join(config.OUTPUTS, "cost_view.csv"), index=False)

    winners = (single.loc[single.groupby(["dataset", "window", "ratio"]).cost.idxmin()]
               .pivot_table(index=["dataset", "window"], columns="ratio", values="method", aggfunc="first"))
    mx = (100 * res.pivot_table(index="method", columns="ratio", values="regret", aggfunc="max")).round(1)
    lines = ["# Cost view of the trade-off curves (generated by code/cost_view.py)", "",
             "Cost per unit of demand in weeks of holding: C(r) = inventory_weeks + r · (1 − fill rate), r = lost-sales "
             "penalty / weekly holding rate. Each method uses its cheapest τ. Regret = cost / cheapest single method − 1.",
             "Reference points: r ≈ 78 for a 20% annual holding rate and a 30% lost margin; r ≈ 650 for the cost "
             "parameters of Theodorou et al. (2025).", "",
             "## 1. Cheapest single method per run and ratio r", "", winners.to_markdown(), "",
             "## 2. Maximum regret over the six runs (%), per ratio r", "", mx.sort_values(100).to_markdown(), ""]
    for (d, w), g in res.groupby(["dataset", "window"], sort=False):
        t = (100 * g.pivot_table(index="method", columns="ratio", values="regret")).round(1)
        lines += [f"## {d}, {w}: regret (%) per ratio r", "", t.sort_values(100).to_markdown(), ""]
    with open(os.path.join(config.OUTPUTS, "cost_view.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("written code/outputs/cost_view.md")


if __name__ == "__main__":
    main()
