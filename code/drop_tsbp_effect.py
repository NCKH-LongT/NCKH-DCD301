"""B5 — which findings change when TSB-P is dropped (8 → 7 methods)?

Compares the standard outputs (8 methods) with the *_m7 outputs written by code/outputs/logs/rerun_m7.sh:
    per-series SQL ranks (stat_tests.csv)            leader and mean ranks of LGB-Q, HGB-Q, TSB-NB
    frontier rank and P(best) (equal_fill_ci*.csv)   leader by dataset, window and demand class
    M5–VN1 rank consistency (Spearman)               by fill rate at τ = 0.9 and by frontier rank
Inventory at equal fill rate, coverage, wQL and all liquidation results of the remaining methods do not
depend on the method set and are not repeated.
Writes code/outputs/drop_tsbp_effect.md.

Usage:
    python code/drop_tsbp_effect.py
"""
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import config  # noqa: E402

WINDOWS = [("main", ""), ("w26", "_w26"), ("w52", "_w52")]
CLASSES = ["all", "smooth", "erratic", "intermittent", "lumpy"]
D = config.DEFAULT


def st(d, sfx, m7):
    return pd.read_csv(os.path.join(config.OUTPUTS, d + sfx + ("_m7" if m7 else ""), "stat_tests.csv"))


def ef(sfx, m7):
    c = pd.read_csv(os.path.join(config.OUTPUTS, f"equal_fill_ci{sfx}{'_m7' if m7 else ''}.csv"))
    return c[c.kpi == "units"]


def fill_ranks(d, sfx, drop):
    k = pd.read_csv(os.path.join(config.OUTPUTS, d + sfx, "kpi.csv"))
    k = k[(k.policy == "none") & (k.tau == D["tau"]) & (k.L == D["L"]) & (k.H == D["H"]) & (k.q_liq == D["q_liq"]) & (k.k == D["k_fixed"])]
    if drop:
        k = k[k.model != "tsb"]
    k = k[k.model != "chronos2"]
    return k.set_index(["group", "model"]).fill_rate


def main():
    lines = ["# B5 — Effect of dropping TSB-P (8 → 7 methods) (generated by code/drop_tsbp_effect.py)", "",
             "“8” = EMP, TSB-P, TSB-NB, ETS, LGB-T, LGB-C, HGB-Q, LGB-Q; “7” = the same without TSB-P.", ""]

    # ---- 1. per-series SQL ranks
    lines += ["## 1. Per-series SQL: best mean rank (leader) and ranks of LGB-Q / HGB-Q / TSB-NB, all series", "",
              "| dataset | window | h | leader, 8 | leader, 7 | LGB-Q 8 → 7 | HGB-Q 8 → 7 | TSB-NB 8 → 7 | CD 8 / 7 | same leader |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    changed = []
    for d in ("M5", "VN1"):
        for w, sfx in WINDOWS:
            a, b = st(d, sfx, False), st(d, sfx, True)
            for h in (3, 13):
                x = a[(a.metric == f"SQL_h{h}") & (a.group == "all")].set_index("model")
                y = b[(b.metric == f"SQL_h{h}") & (b.group == "all")].set_index("model")
                la, lb = x.mean_rank.idxmin(), y.mean_rank.idxmin()
                same = la == lb
                if not same:
                    changed.append(f"per-series SQL leader, {d} {w} h={h}: {la} → {lb}")
                r = lambda m: f"{x.mean_rank[m]:.2f} → {y.mean_rank[m]:.2f}"
                lines.append(f"| {d} | {w} | {h} | {la} | {lb} | {r('lgb_quantile')} | {r('hgb_quantile')} | {r('tsb_nb')} | "
                             f"{x.nemenyi_cd.iloc[0]:.3f} / {y.nemenyi_cd.iloc[0]:.3f} | {'yes' if same else 'NO'} |")
    lines.append("")
    lines += ["### VN1 by demand class, h = 3: leader with 8 → with 7 methods", "", "| window | " + " | ".join(CLASSES[1:]) + " |", "|---|---|---|---|---|"]
    for w, sfx in WINDOWS:
        a, b = st("VN1", sfx, False), st("VN1", sfx, True)
        cells = []
        for g in CLASSES[1:]:
            x = a[(a.metric == "SQL_h3") & (a.group == g)].set_index("model").mean_rank
            y = b[(b.metric == "SQL_h3") & (b.group == g)].set_index("model").mean_rank
            cells.append(f"{x.idxmin()} → {y.idxmin()}")
            if x.idxmin() != y.idxmin():
                changed.append(f"per-series SQL leader, VN1 {w} {g} h=3: {x.idxmin()} → {y.idxmin()}")
        lines.append(f"| {w} | " + " | ".join(cells) + " |")
    lines.append("")

    # ---- 2. frontier
    lines += ["## 2. Frontier rank: leader (rank, P(best)) with 8 → with 7 methods", "",
              "| dataset | window | " + " | ".join(CLASSES) + " |", "|---|---|" + "---|" * len(CLASSES)]
    fr = {}
    for w, sfx in WINDOWS:
        a, b = ef(sfx, False), ef(sfx, True)
        for d in ("M5", "VN1"):
            cells = []
            for g in CLASSES:
                x = a[(a.dataset == d) & (a.group == g)].set_index("model")
                y = b[(b.dataset == d) & (b.group == g)].set_index("model")
                fr[d, w, g, 8], fr[d, w, g, 7] = x.frontier_rank, y.frontier_rank
                if x.frontier_rank.isna().all() or y.frontier_rank.isna().all():
                    cells.append("n/a")
                    continue
                la, lb = x.frontier_rank.idxmin(), y.frontier_rank.idxmin()
                cells.append(f"{la} ({x.frontier_rank[la]:.2f}, {x.best_frontier_share[la]:.2f}) → "
                             f"{lb} ({y.frontier_rank[lb]:.2f}, {y.best_frontier_share[lb]:.2f})")
                if la != lb:
                    changed.append(f"frontier leader, {d} {w} {g}: {la} → {lb}")
            lines.append(f"| {d} | {w} | " + " | ".join(cells) + " |")
    lines.append("")

    # ---- 3. Spearman
    lines += ["## 3. M5–VN1 rank consistency (Spearman ρ) with 8 → with 7 methods", "",
              "| ranking | window | " + " | ".join(CLASSES) + " |", "|---|---|" + "---|" * len(CLASSES)]
    for w, sfx in WINDOWS:
        cells = []
        for g in CLASSES:
            out = []
            for drop in (False, True):
                a, b = fill_ranks("M5", sfx, drop), fill_ranks("VN1", sfx, drop)
                x, y = a.loc[g], b.loc[g]
                c = x.index.intersection(y.index)
                out.append(stats.spearmanr(x[c], y[c]).statistic)
            cells.append(f"{out[0]:.2f} → {out[1]:.2f}")
        lines.append(f"| fill rate at τ = 0.9 | {w} | " + " | ".join(cells) + " |")
    for w, sfx in WINDOWS:
        cells = []
        for g in CLASSES:
            out = []
            for n in (8, 7):
                x, y = fr["M5", w, g, n], fr["VN1", w, g, n]
                c = x.dropna().index.intersection(y.dropna().index)
                out.append(stats.spearmanr(x[c], y[c]).statistic if len(c) > 2 else np.nan)
            cells.append("n/a" if not np.isfinite(out[0]) or not np.isfinite(out[1]) else f"{out[0]:.2f} → {out[1]:.2f}")
        lines.append(f"| frontier rank | {w} | " + " | ".join(cells) + " |")
    lines += ["", "## 4. Findings whose leader changes", ""]
    lines += [f"- {c}" for c in changed] or ["- none"]
    lines.append("")
    with open(os.path.join(config.OUTPUTS, "drop_tsbp_effect.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("written code/outputs/drop_tsbp_effect.md")


if __name__ == "__main__":
    main()
