"""B4 — does the unsupervised segmentation improve on the ADI–CV² classes? (criteria fixed in phase2_workflow.md)

    C1  overlap with ADI–CV² (reported by segment_series.py)
    C2  share of the variance of the per-series accuracy difference LGB-Q vs TSB-NB explained by the grouping (η²),
        for (a) the indicator "LGB-Q has the lower SQL" and (b) the winsorised log ratio of the two SQLs
    C3  stability of the group-level frontier leader across the three test windows
    C4  decision value: a rule "use the method that was most inventory-efficient for this group in the previous
        window" is learned on window t−1 and applied to window t; the composite policy is compared, at equal fill
        rate, with always using LGB-Q and with the single best method of the previous window (bootstrap CIs)
Seven methods (TSB-P excluded). Only cached forecasts are used.
Writes code/outputs/segment_eval.md and .csv.

Usage:
    python code/segment_eval.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_results import frontier_rank  # noqa: E402
from equal_fill_ci import totals  # noqa: E402
from f2d import config  # noqa: E402

MODELS = ["empirical", "tsb_nb", "ets", "lgb_tweedie", "lgb_conformal", "hgb_quantile", "lgb_quantile"]
TARGETS = (0.90, 0.92, 0.94, 0.96, 0.98)
EVAL_TARGETS = (0.90, 0.92, 0.94)
WINDOWS = [("w52", 52), ("w26", 26), ("main", 0)]
N_BOOT = 200
GROUPINGS = {"ADI–CV²": "demand_class", "segments": "segment", "ADI–CV² × segments": "both"}


def eta2(v, g):
    ok = np.isfinite(v)
    v, g = v[ok], g[ok]
    tot = ((v - v.mean()) ** 2).sum()
    between = sum(len(x) * (x.mean() - v.mean()) ** 2 for x in (v[g == c] for c in np.unique(g)))
    return between / tot if tot > 0 else np.nan


def curve(tot, method_of_series, idx=None):
    """Fill rate and inventory (weeks of demand) over the τ grid when series i uses method_of_series[i]."""
    f, i = [], []
    sl = slice(None) if idx is None else idx
    dem = tot["demand"][sl].sum()
    for t in config.TAU_GRID:
        sales = np.zeros(len(tot["demand"]))
        onh = np.zeros(len(tot["demand"]))
        for m in np.unique(method_of_series):
            k = method_of_series == m
            sales[k] = tot[m, t, "sales"][k]
            onh[k] = tot[m, t, "onhand"][k]
        f.append(sales[sl].sum() / dem)
        i.append(onh[sl].sum() / dem)
    return np.maximum.accumulate(np.array(f)), np.array(i)


def inv_at(f, i, target):
    return np.interp(target, f, i) if f.min() <= target <= f.max() else np.nan


def group_leader(tot, mask):
    """Method with the best frontier rank inside a group (None if no fill target is reached by two methods)."""
    rows = {}
    dem = tot["demand"][mask].sum()
    if dem <= 0:
        return None, None
    for m in MODELS:
        f = np.maximum.accumulate(np.array([tot[m, t, "sales"][mask].sum() / dem for t in config.TAU_GRID]))
        i = np.array([tot[m, t, "onhand"][mask].sum() / dem for t in config.TAU_GRID])
        rows[m] = {t: inv_at(f, i, t) for t in TARGETS}
    fr = frontier_rank(pd.DataFrame(rows).T)
    if fr.isna().all():
        return None, None
    return fr.idxmin(), fr


def main():
    lines = ["# B4 — Segmentation vs ADI–CV² classes (generated by code/segment_eval.py)", "",
             "Seven methods (TSB-P excluded). Segments S1–S3 from code/segment_series.py (fitted on window w52).", ""]
    data_ = {}
    for d in ("M5", "VN1"):
        for w, off in WINDOWS:
            seg = pd.read_parquet(os.path.join(config.CACHE, f"segments_{d}_{w}.parquet"))
            met = pd.read_parquet(os.path.join(config.CACHE, f"series_metrics_{d}{'_' + w if off else ''}.parquet"))
            tot = totals(d, off, MODELS)
            assert (seg.series_id.values == met.series_id.values).all() and len(seg) == len(tot["demand"])
            seg["segment"] = "S" + seg.segment.astype(str)
            seg["both"] = seg.demand_class + "/" + seg.segment
            data_[d, w] = (seg, met, tot)
            print(d, w, "loaded", flush=True)

    # ---- C2
    rows = []
    for (d, w), (seg, met, _) in data_.items():
        for h in (3, 13):
            a, b = met[f"lgb_quantile|SQL_h{h}"].to_numpy(float), met[f"tsb_nb|SQL_h{h}"].to_numpy(float)
            win = np.where(np.isfinite(a) & np.isfinite(b), (a < b).astype(float), np.nan)
            lr = np.log((b + 0.01) / (a + 0.01))
            lo, hi = np.nanpercentile(lr, [1, 99])
            lr = np.clip(lr, lo, hi)
            for name, col in GROUPINGS.items():
                g = seg[col].to_numpy()
                rows.append(dict(dataset=d, window=w, h=h, grouping=name, n_groups=len(np.unique(g)),
                                 eta2_win=eta2(win, g), eta2_logratio=eta2(lr, g)))
    c2 = pd.DataFrame(rows)
    lines += ["## C2. Variance of the LGB-Q vs TSB-NB accuracy difference explained by the grouping (η², %)", "",
              "win = indicator that LGB-Q has the lower per-series SQL; log ratio = log(SQL_TSB-NB / SQL_LGB-Q), winsorised at 1–99%.", ""]
    for stat in ("eta2_win", "eta2_logratio"):
        t = c2.pivot_table(index=["dataset", "h", "grouping"], columns="window", values=stat, sort=False)[[w for w, _ in WINDOWS]]
        lines += [f"**{stat}**", "", (100 * t).round(2).to_markdown(), ""]

    # ---- C3
    lead = []
    for (d, w), (seg, _, tot) in data_.items():
        for name, col in (("ADI–CV²", "demand_class"), ("segments", "segment")):
            for g in sorted(seg[col].unique()):
                m, fr = group_leader(tot, (seg[col] == g).to_numpy())
                lead.append(dict(dataset=d, window=w, grouping=name, group=g, leader=m or "n/a",
                                 n=int((seg[col] == g).sum()),
                                 runner_up="n/a" if fr is None else fr.sort_values().index[1],
                                 gap=np.nan if fr is None else fr.sort_values().iloc[1] - fr.min()))
    lead = pd.DataFrame(lead)
    t = lead.pivot_table(index=["dataset", "grouping", "group"], columns="window", values="leader", aggfunc="first", sort=False)[[w for w, _ in WINDOWS]]
    t["stable"] = [("yes" if len(set(r)) == 1 and "n/a" not in set(r) else "no") for r in t.to_numpy()]
    lines += ["## C3. Frontier leader by group in the three windows", "", t.to_markdown(), ""]
    st = t.reset_index().groupby(["dataset", "grouping"]).stable.apply(lambda s: f"{(s == 'yes').sum()} of {len(s)}")
    lines += ["Groups with the same leader in all three windows: " + "; ".join(f"{d} {g}: {v}" for (d, g), v in st.items()), ""]

    # ---- C4
    rng = np.random.default_rng(config.SEED)
    res = []
    for d in ("M5", "VN1"):
        for (w0, _), (w1, _) in zip(WINDOWS[:-1], WINDOWS[1:]):
            seg0, _, tot0 = data_[d, w0]
            seg1, _, tot1 = data_[d, w1]
            n1 = len(seg1)
            overall, _ = group_leader(tot0, np.ones(len(seg0), bool))
            rules = {"always LGB-Q": np.array(["lgb_quantile"] * n1),
                     "always TSB-NB": np.array(["tsb_nb"] * n1),
                     "best single method of previous window": np.array([overall] * n1)}
            chosen = {}
            for name, col in (("rule by ADI–CV² class", "demand_class"), ("rule by segment", "segment"), ("rule by class × segment", "both")):
                pick = {}
                for g in seg1[col].unique():
                    m0 = (seg0[col] == g).to_numpy()
                    m, _ = group_leader(tot0, m0) if m0.sum() >= 50 else (None, None)
                    pick[g] = m or overall
                rules[name] = seg1[col].map(pick).to_numpy()
                chosen[name] = pick
            # oracle by segment (learned on the test window itself): upper bound, not a usable rule
            pick = {g: (group_leader(tot1, (seg1["segment"] == g).to_numpy())[0] or overall) for g in seg1["segment"].unique()}
            rules["oracle by segment (not usable)"] = seg1["segment"].map(pick).to_numpy()
            base = {}
            curves = {r: curve(tot1, mth) for r, mth in rules.items()}
            boots = [rng.integers(0, n1, n1) for _ in range(N_BOOT)]
            bc = {r: [curve(tot1, mth, b) for b in boots] for r, mth in rules.items()}
            for r in rules:
                row = dict(dataset=d, transition=f"{w0} → {w1}", rule=r,
                           choices="" if r not in chosen else "; ".join(f"{g}: {m}" for g, m in sorted(chosen[r].items())))
                for tg in EVAL_TARGETS:
                    v = inv_at(*curves[r], tg)
                    ref = inv_at(*curves["always LGB-Q"], tg)
                    row[f"inv_{tg:.2f}"] = v
                    rel = np.array([inv_at(*bc[r][k], tg) / inv_at(*bc["always LGB-Q"][k], tg) - 1 for k in range(N_BOOT)])
                    okb = np.isfinite(rel)
                    row[f"rel_{tg:.2f}"] = v / ref - 1 if np.isfinite(v) and np.isfinite(ref) else np.nan
                    if okb.mean() >= 0.95:
                        row[f"lo_{tg:.2f}"], row[f"hi_{tg:.2f}"] = np.percentile(rel[okb], [2.5, 97.5])
                    else:
                        row[f"lo_{tg:.2f}"] = row[f"hi_{tg:.2f}"] = np.nan
                res.append(row)
            print(d, w0, w1, "rules done", flush=True)
    res = pd.DataFrame(res)
    res.to_csv(os.path.join(config.OUTPUTS, "segment_eval.csv"), index=False)

    def cell(r, tg):
        v, rel, lo, hi = r[f"inv_{tg:.2f}"], r[f"rel_{tg:.2f}"], r[f"lo_{tg:.2f}"], r[f"hi_{tg:.2f}"]
        if not np.isfinite(v):
            return "—"
        s = f"{v:.2f} ({100 * rel:+.1f}%"
        return s + (f" [{100 * lo:+.1f}, {100 * hi:+.1f}])" if np.isfinite(lo) else ")")
    lines += ["## C4. Selection rules learned on the previous window, applied to the next one", "",
              "Inventory (weeks of demand) needed at a fill rate, all series; in brackets the difference to always using LGB-Q "
              "with a 95% bootstrap CI over series (negative = less inventory than LGB-Q).", ""]
    for (d, tr), g in res.groupby(["dataset", "transition"], sort=False):
        lines += [f"### {d}, {tr}", "", "| rule | fill 0.90 | fill 0.92 | fill 0.94 |", "|---|---|---|---|"]
        for _, r in g.iterrows():
            lines.append(f"| {r.rule} | {cell(r, 0.90)} | {cell(r, 0.92)} | {cell(r, 0.94)} |")
        lines.append("")
        for _, r in g[g.choices != ""].iterrows():
            lines.append(f"- {r.rule}: {r.choices}")
        lines.append("")
    with open(os.path.join(config.OUTPUTS, "segment_eval.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("written code/outputs/segment_eval.md")


if __name__ == "__main__":
    main()
