"""Descriptive (ex-post) analysis of the VN1 period dependence (reviewer points B2/B3).

For each dataset × test window, series are split by the change of their demand between the 26 weeks before
the test period and the test period itself (KPI weeks rescaled to 26 weeks):
    shrinking   test < 0.67 × previous
    stable      0.67–1.5 ×
    growing     > 1.5 × (includes series with no sale in the previous 26 weeks and sales in the test period)
The split uses realised test demand, so it cannot be used for decisions; it only describes where each method
gains or loses. For every stratum the default policy (L = 2, R = 1, no liquidation) is simulated over the τ grid
and the inventory needed to reach a fill rate is interpolated as in analyze_results.py.
Writes code/outputs/demand_shift.csv and demand_shift.md.

Usage:
    python code/demand_shift_analysis.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from f2d import classify, config, data, policy  # noqa: E402

MODELS = ["tsb_nb", "ets", "lgb_tweedie", "lgb_conformal", "hgb_quantile", "lgb_quantile"]
TARGETS = (0.90, 0.92, 0.94)
RUNS = [("M5", 0), ("M5", 26), ("M5", 52), ("VN1", 0), ("VN1", 26), ("VN1", 52)]
STRATA = ["shrinking", "stable", "growing"]


def run(name, offset):
    d = config.DEFAULT
    L, h = d["L"], d["L"] + d["R"]
    p = data.load(name)
    if offset:
        p = data.truncate(p, p["Y"].shape[1] - offset)
    Y = p["Y"]
    T = Y.shape[1]
    test0 = T - config.TEST_WEEKS
    sel = p["start"] <= test0 - config.VALID_WEEKS
    cls, _, _ = classify.classify(Y, p["start"], test0)
    sel &= cls != "none"
    idx = np.flatnonzero(sel)
    Y0 = np.nan_to_num(Y)[idx]
    D = Y0[:, test0:T].astype(np.float64)
    w = slice(config.WARMUP_WEEKS, None)
    prev = Y0[:, test0 - 26:test0].sum(1)
    test = D[:, w].sum(1) * 26 / D[:, w].shape[1]
    ratio = np.where(prev > 0, test / np.maximum(prev, 1e-9), np.where(test > 0, np.inf, 1.0))
    stratum = np.where(ratio < 0.67, "shrinking", np.where(ratio > 1.5, "growing", "stable"))
    fc = os.path.join(config.CACHE, "forecasts", name + (f"_w{offset}" if offset else ""))
    qs = list(config.QUANTILES)
    dem = D[:, w].sum(1)
    tot = {}
    for m in MODELS:
        Q = np.load(os.path.join(fc, f"{m}_h{h}.npz"))["Q"][idx]
        for tau in config.TAU_GRID:
            S = Q[:, :, qs.index(tau)]
            sim = policy.simulate(D, S, np.full_like(S, np.inf), L)
            tot[m, tau] = (sim["sales"][:, w].sum(1), sim["on_hand_end"][:, w].sum(1))
    rows = []
    window = f"w{offset}" if offset else "main"
    for s in STRATA + ["all"]:
        mask = np.ones(len(idx), bool) if s == "all" else stratum == s
        r0 = dict(dataset=name, window=window, stratum=s, n_series=int(mask.sum()),
                  demand_share=dem[mask].sum() / dem.sum(), test_vs_prev=test[mask].sum() / max(prev[mask].sum(), 1))
        for m in MODELS:
            f_ = np.array([tot[m, t][0][mask].sum() / dem[mask].sum() for t in config.TAU_GRID])
            i_ = np.array([tot[m, t][1][mask].sum() / dem[mask].sum() for t in config.TAU_GRID])
            f_ = np.maximum.accumulate(f_)
            r = dict(r0, model=m, fill_tau09=f_[list(config.TAU_GRID).index(0.9)],
                     inv_tau09=i_[list(config.TAU_GRID).index(0.9)])
            for t in TARGETS:
                r[f"inv_{t:.2f}"] = np.interp(t, f_, i_) if f_.min() <= t <= f_.max() else np.nan
            rows.append(r)
    return pd.DataFrame(rows)


def main():
    out = pd.concat([run(n, o) for n, o in RUNS], ignore_index=True)
    out.to_csv(os.path.join(config.OUTPUTS, "demand_shift.csv"), index=False)
    lines = ["# Demand shift between history and test period (generated by code/demand_shift_analysis.py)", "",
             "Strata by realised change of demand (test period vs the 26 weeks before it): shrinking < 0.67×, "
             "stable 0.67–1.5×, growing > 1.5×. Ex-post split: descriptive only.", "",
             "## Composition", "", "| dataset | window | stratum | series | share of test demand | test / previous 26 weeks |", "|---|---|---|---|---|---|"]
    comp = out.drop_duplicates(["dataset", "window", "stratum"])
    for _, r in comp.iterrows():
        lines.append(f"| {r.dataset} | {r.window} | {r.stratum} | {r.n_series:,} | {100 * r.demand_share:.1f}% | {r.test_vs_prev:.2f} |")
    lines += ["", "## Inventory (weeks of demand) needed at fill rate 0.92, by stratum", "",
              "Δ = I_TSB-NB / I_LGB-Q − 1 (positive = LGB-Q needs less). “—” = target outside the range reached.", "",
              "| dataset | window | stratum | LGB-Q | TSB-NB | Δ | LGB-T | LGB-C | HGB-Q | ETS |", "|---|---|---|---|---|---|---|---|---|---|"]

    def f(v):
        return "—" if not np.isfinite(v) else f"{v:.2f}"
    for (d, w, s), g in out.groupby(["dataset", "window", "stratum"], sort=False):
        g = g.set_index("model")["inv_0.92"]
        a, b = g["lgb_quantile"], g["tsb_nb"]
        delta = f"{100 * (b / a - 1):+.1f}%" if np.isfinite(a) and np.isfinite(b) else "—"
        lines.append(f"| {d} | {w} | {s} | {f(a)} | {f(b)} | {delta} | {f(g['lgb_tweedie'])} | {f(g['lgb_conformal'])} | "
                     f"{f(g['hgb_quantile'])} | {f(g['ets'])} |")
    lines += ["", "## Fill rate at τ = 0.9, by stratum", "", "| dataset | window | stratum | LGB-Q | TSB-NB | LGB-T | ETS |", "|---|---|---|---|---|---|---|"]
    for (d, w, s), g in out.groupby(["dataset", "window", "stratum"], sort=False):
        g = g.set_index("model")["fill_tau09"]
        lines.append(f"| {d} | {w} | {s} | {g['lgb_quantile']:.3f} | {g['tsb_nb']:.3f} | {g['lgb_tweedie']:.3f} | {g['ets']:.3f} |")
    with open(os.path.join(config.OUTPUTS, "demand_shift.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("written code/outputs/demand_shift.md")


if __name__ == "__main__":
    main()
